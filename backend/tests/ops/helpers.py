def run_git(repo: Path, *args: str) -> str:
    env = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.com",
           "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.com",
           "GIT_AUTHOR_DATE": "2026-09-20T12:00:00Z", "GIT_COMMITTER_DATE": "2026-09-20T12:00:00Z"}
    return subprocess.run(["git", "-C", str(repo), "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false", "-c", "core.hooksPath=/dev/null", *args],
                          check=True, capture_output=True, text=True, env=env).stdout.strip()


def write_files(repo: Path, files: dict[str, str]) -> None:
    for name, content in files.items():
        target = repo / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)


def make_repo(tmp_path: Path, files: dict[str, str] | None = None, *, with_origin: bool = True) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir(parents=True)
    run_git(repo, "init", "-q", "-b", "main")
    write_files(repo, {**BASE_FILES, **(files or {})})
    run_git(repo, "add", "-A")
    run_git(repo, "commit", "-q", "-m", "initial")
    if with_origin:
        origin = tmp_path / "origin.git"
        subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(origin)], check=True)
        run_git(repo, "remote", "add", "origin", str(origin))
        run_git(repo, "push", "-q", "origin", "main")
        run_git(repo, "fetch", "-q", "origin")
    return repo


def commit(repo: Path, files: dict[str, str], message: str = "change", *, push: bool = False) -> str:
    write_files(repo, files)
    run_git(repo, "add", "-A")
    run_git(repo, "commit", "-q", "-m", message)
    if push:
        run_git(repo, "push", "-q", "origin", "main")
        run_git(repo, "fetch", "-q", "origin")
    return run_git(repo, "rev-parse", "HEAD")


def build(repo: Path, out: Path, *, ref: str = "origin/main", rehearsal: bool = False, when: datetime = NOW) -> br.BuildResult:
    return br.build_release(repo, out, ref=ref, rehearsal=rehearsal, release_time=when)


# --- tar helpers (to craft hostile archives) -----------------------------------------

def rewrite_tar(artifact: Path, mutate, *, fix_sidecar: bool = True) -> Path:
    """Read a built artifact's members, let ``mutate(dict name->bytes)`` edit
    them, write a new tar next to it with a *valid* sidecar for the new bytes
    (so only the layers under test can object)."""
    import gzip, io, tarfile

    members: dict[str, bytes] = {}
    with tarfile.open(artifact, "r:gz") as tar:
        for m in tar:
            members[m.name] = tar.extractfile(m).read()
    mutate(members)
    out = artifact.with_name(artifact.name.replace(".tar.gz", "-x.tar.gz"))
    out = artifact  # keep the canonical name: the id in the file name must still match
    raw = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as gz:
        with tarfile.open(fileobj=gz, mode="w", format=tarfile.USTAR_FORMAT) as tar:
            for name in sorted(members):
                info = tarfile.TarInfo(name)
                info.size = len(members[name]); info.mode = 0o644
                tar.addfile(info, io.BytesIO(members[name]))
    out.write_bytes(raw.getvalue())
    if fix_sidecar:
        out.with_name(out.name + ".sha256").write_text(f"{rc.sha256_bytes(raw.getvalue())}  {out.name}\n")
    return out


