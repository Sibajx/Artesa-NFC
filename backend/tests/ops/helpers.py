class Scenario:
    """Root + repo + World + a ctx factory. ``release()`` commits a change,
    builds a real artifact from it and installs it as a prepared release."""

    def __init__(self, tmp_path: Path) -> None:
        self.tmp = tmp_path
        self.root = tmp_path / "artesa-nfc"
        for d in ("bin", "incoming", "releases", "shared/backups", "shared/state", "shared/deploys"):
            (self.root / d).mkdir(parents=True, exist_ok=True)
        os.chmod(self.root / "shared", 0o700)
        write_env(self.root)
        self.repo = make_repo(tmp_path)
        self.world = World(self.root)
        self.sink = Sink()
        self._n = 0
        self.ids: dict[str, str] = {}
        self.artifacts: dict[str, Path] = {}

    def release(self, name: str, files: dict[str, str] | None = None, *, prepared: bool = True, channel_rehearsal: bool = True) -> str:
        self._n += 1
        commit(self.repo, files or {f"backend/app/rev_{self._n}.py": f"N = {self._n}\n"}, f"release {name}")
        result = build(self.repo, self.root / "incoming", ref="HEAD", rehearsal=channel_rehearsal, when=NOW + timedelta(minutes=self._n))
        self.artifacts[name] = result.artifact
        rid = install_release(self.root, result.artifact, prepared=prepared)
        self.ids[name] = rid
        return rid

    def activate(self, current: str, previous: str | None = None) -> None:
        link(self.root, "current", self.ids[current])
        if previous:
            link(self.root, "previous", self.ids[previous])
        self.world.serving = self.ids[current]

    def ctx(self, **kw) -> ad.Context:
        self.sink = Sink()
        return make_ctx(self.world, self.sink, **kw)

    def run(self, argv: list[str], **kw) -> int:
        ctx = self.ctx(**kw)
        self.last_ctx = ctx
        return ad.main(["--root", str(self.root), "--rehearsal", "--prod-port", "18000", "--candidate-port", "18001", *argv], ctx)

    def current(self) -> str | None:
        return dl.read_link(dl.Layout(self.root), self.root / "current")

    def previous(self) -> str | None:
        return dl.read_link(dl.Layout(self.root), self.root / "previous")

    def log_events(self) -> list[dict]:
        path = self.root / "shared" / "state" / "deploy-log.jsonl"
        return [json.loads(line) for line in path.read_text().splitlines()] if path.exists() else []

    def record_rehearsal(self, revision: str | None = "bbb222") -> None:
        """Kept for older scenarios: a standalone restore-check record. It no
        longer authorizes anything (deploy restore-checks its own backup)."""
        import deploy_db as ddb
        report = ddb.RestoreReport("f" * 64, revision, True, [])
        ddb.record_rehearsal(dl.Layout(self.root), lambda: NOW, report, "ok")

    def evidence_dirs(self) -> list[Path]:
        root = self.root / "shared" / "state" / "deployments"
        return sorted(root.iterdir()) if root.exists() else []

    def evidence(self, name: str, index: int = -1) -> dict:
        return json.loads((self.evidence_dirs()[index] / name).read_text())


